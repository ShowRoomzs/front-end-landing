// Generates src/styles/pretendard.css from the `pretendard` package's static
// dynamic-subset stylesheet, keeping only the weights the site uses and only
// woff2 sources. URLs point at the `@pretendard-subset` alias (vite.config.ts)
// so Vite copies just the referenced files into dist — no CDN at runtime.
// Usage: node scripts/gen-pretendard-css.mjs
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const src = path.join(
  root,
  "node_modules/pretendard/dist/web/static/pretendard-dynamic-subset.css"
)
const out = path.join(root, "src/styles/pretendard.css")
const WEIGHTS = new Set(["400", "500", "600", "700", "800", "900"])

const css = fs.readFileSync(src, "utf8")
const header = css.slice(0, css.indexOf("*/") + 2)
const faces = [...css.matchAll(/@font-face\s*\{[^}]*\}/g)].map(m => m[0])
const kept = faces
  .filter(face => WEIGHTS.has(/font-weight:\s*(\d+)/.exec(face)[1]))
  .map(face =>
    face
      .replace(
        /src:[^;]*;/,
        s =>
          `src: url(@pretendard-subset/${/woff2-dynamic-subset\/([^)]+)\)/.exec(s)[1]}) format("woff2");`
      )
      .replace(/\t/g, "  ")
      .replace(/'/g, '"')
  )
const body = [
  header,
  "/* Generated by scripts/gen-pretendard-css.mjs from pretendard@1.3.9 — do not edit. */",
  ...kept,
].join("\n")
fs.writeFileSync(out, body + "\n")
console.log(`kept ${kept.length} of ${faces.length} @font-face rules`)
